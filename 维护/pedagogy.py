def array_literals(text):
 """Read literal lists from authored question text, without executing them."""
 out=[];depth=0;start=None;quote=None
 for i,ch in enumerate(text):
  if quote:
   if ch==quote and (i==0 or text[i-1]!='\\'):quote=None
   continue
  if ch in "'\"":quote=ch;continue
  if ch=='[':
   if depth==0:start=i
   depth+=1
  elif ch==']'and depth:
   depth-=1
   if not depth:
    try:out.append(ast.literal_eval(text[start:i+1]))
    except (ValueError,SyntaxError):pass
 return out

