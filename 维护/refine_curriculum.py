def add_fixed_bst(review):
    # PDF p8: preserve the actual empty shape; letters only name locations for answer input.
    shape={'A':('B','C'),'B':('D','E'),'C':('F',None),'D':(None,'G'),
           'E':(None,None),'F':('H','I'),'G':(None,None),'H':(None,None),'I':(None,None)}
    balanced={'A':('B','C'),'B':('D','E'),'C':('F','G'),'D':(None,None),
              'E':(None,None),'F':(None,None),'G':(None,None)}
    def case(tree,keys,id,variant,manual=False):
        ino=[];depth={}
        def walk(u,d=1):
            if u is None:return
            left,right=tree[u];depth[u]=d;walk(left,d+1);ino.append(u);walk(right,d+1)
        walk('A');values=dict(zip(ino,sorted(keys)));labels=sorted(tree)
        # Inorder x coordinates ensure left/right drawing positions never swap.
        points={u:[40+520*(ino.index(u)+.5)/len(ino),35+(depth[u]-1)*90]for u in labels}
        given=dict(kind='tree',caption='给定树形：字母是位置标签，不是待填关键字',
            nodes=labels,points=[points[u]for u in labels],
            links=[[u,v,direction]for u in labels for v,direction in zip(tree[u],['左','右'])if v],
            rows=[[u,tree[u][0]or'∅',tree[u][1]or'∅']for u in labels],height=70+90*(max(depth.values())-1))
        total=sum(depth.values());asl=str(__import__('fractions').Fraction(total,len(keys)))
        q=dict(id=id,chapter=5,mode='review',family='R5-fixed-shape',variant=variant,topic='r5-7',
            type='written'if manual else'fields',points=8,
            difficulty='综合拔高'if len(keys)>7 or manual else'考试标准',
            title=f'保持下方树形不变，把互异关键字 {keys} 各填一次，使它成为BST。'+('在纸上填树，并写出每个位置的值及等概率成功ASL。'if manual else'按位置标签顺序 '+','.join(labels)+' 填出键值序列，再求等概率成功ASL。')+'根比较计1次。',
            given=given,pages='48–53',sourcePages=[8],
            origin='原卷树形整理并加位置标签'if len(keys)==9 else'同类考法新题',
            hint='BST中序必须递增；先写位置的中序，再把排好序的关键字依次放进去。',
            support=dict(ask='给的是形状，形状不能改；这次不按输入次序插入新树。',
                plan=['先按左、根、右写出位置标签的中序，再依次赋递增键。','赋值完成后按给定形状数层数，根1层，ASL取全部层数的等概率平均。'],
                format='字母仅标位置；保持空孩子与左右方向。数值序列用逗号分隔；ASL可填分数。'),
            solution=['位置中序为 '+','.join(ino)+'，应按该顺序放递增关键字。',
                      '各位置填值：'+'；'.join(u+'='+str(values[u])for u in labels)+'。',
                      f'层数和={total}；等概率成功ASL={asl}。同一固定形状下，互异键的具体大小不改变这组层数。'],
            worked=[dict(caption='先确定中序位置，再对应递增键',heads=['中序次序','位置标签','填入键','层数/比较次数'],
                         rows=[[str(i+1),u,str(values[u]),str(depth[u])]for i,u in enumerate(ino)])],rubric=[])
        q['explain']=' '.join(q['solution'])
        if manual:q['rubric']=[dict(label='全部位置赋值正确，BST中序递增且给定形状不变',points=6),dict(label=f'根计1次，成功ASL={asl}，分母为{len(keys)}',points=2)]
        else:q['fields']=[dict(label='按 '+','.join(labels)+' 顺序填各位置的键值',answer=','.join(str(values[u])for u in labels),points=6,kind='sequence',aliases=[]),dict(label='等概率成功 ASL',answer=asl,points=2,kind='number',aliases=[])]
        return q
    review.extend([case(shape,list(range(1,10)),'BST-shape-1',1),
                   case(balanced,[2,4,6,8,10,12,14],'BST-shape-2',2),
                   case(shape,list(range(1,10)),'BST-shape-paper',3,True)])

def align_integrated_tasks(review):
    from fractions import Fraction
    import re,ast
    for q in review:
        if q['family']=='R6-shortestpath':
            edges=ast.literal_eval(re.search(r'\[[^\]]+\]',q['title']).group())
            end=max(max(u,v)for u,v,w in edges);paths=[]
            def visit(u,path,cost):
                if u==end:paths.append((cost,path));return
                for a,b,w in edges:
                    if a==u and b not in path:visit(b,path+[b],cost+w)
            visit(1,[1],0)
            optimum=min(d for d,p in paths)
            answers=[','.join(map(str,p))for d,p in paths if d==optimum]
            q['fields'][0]['aliases']=[s for s in answers if s!=q['fields'][0]['answer']]
            if len(answers)>1:
                q['title']+='存在多条等长最短路时，任意一条最短简单路径均可。'
